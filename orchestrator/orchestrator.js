// Entry point of the distributed k6 orchestrator.
//
// The code is split by responsibility (readable "per controller / socket"):
//
//   constants.js   memory / console caps
//   utils.js       formatting (dates, bytes)
//   state.js       in-memory registry: workers + sessions (source of truth)
//   metrics.js     k6 metrics aggregation + per-second snapshot
//   workers.js     worker events: k6 logs + end of test
//   scripts.js     k6 script validation (Node.js imports detection)
//   reports/       session reports (JSON, TXT, self-contained HTML)
//   routes.js      HTTP API (controllers)
//   sockets.js     Socket.io channel (workers + web console)
//
// This file only assembles them: express + socket.io + listen.
import express from 'express';
import { createServer } from 'http';
import { Server } from 'socket.io';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { registerRoutes } from './routes.js';
import { registerSockets } from './sockets.js';
import { startMetricsTicker } from './metrics.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORT = process.env.PORT || 3000;

const app = express();
const httpServer = createServer(app);
// Socket.io configuration with open CORS to let the workers connect
const io = new Server(httpServer, {
  cors: { origin: '*', methods: ['GET', 'POST'] }
});

app.use(express.json());
// Web console: the Next.js build (web/out), on the same origin as the API and
// Socket.io. `web/out` is a static build generated by `cd web && npm run build`.
const nextOut = path.join(__dirname, '..', 'web', 'out');
app.use(express.static(nextOut));
if (!fs.existsSync(nextOut)) {
  console.warn(
    '\x1b[33m' +
      '[Orchestrator] Warning: the web console build (web/out) is missing.\n' +
      '          Generate it with `cd web && npm run build`, otherwise the console is empty.\x1b[0m'
  );
}

// Wiring: HTTP API + Socket.io channel + metrics snapshot (1/s)
registerRoutes(app, io);
registerSockets(io);
startMetricsTicker(io);

// Starting the orchestration server
httpServer.listen(PORT, () => {
  console.log(`\x1b[32m%s\x1b[0m`, `[Orchestrator] Server started on port ${PORT}`);
  console.log(`[Orchestrator] Web console available on http://localhost:${PORT}`);
  console.log('[Orchestrator] Waiting for worker connections on the socket.io protocol...');
});